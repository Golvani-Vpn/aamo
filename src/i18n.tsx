export const getTranslation = (lang: LanguageCode, key: string, defaultText?: string): string => {
  return translations[lang]?.[key] || translations['en']?.[key] || defaultText || key;
};

interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, defaultText?: string) => string;
  dir: 'rtl' | 'ltr';
  currentLangOption: LanguageOption;
}

export const LanguageContext = createContext<LanguageContextType>({
  language: 'fa',
  setLanguage: () => {},
  t: (key: string) => key,
  dir: 'rtl',
  currentLangOption: SUPPORTED_LANGUAGES[0],
});

export const useLanguage = () => useContext(LanguageContext);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const saved = localStorage.getItem('apkforge_language') as LanguageCode;
    if (saved && SUPPORTED_LANGUAGES.some(l => l.code === saved)) {
      return saved;
    }
    return 'fa';
  });

  const currentLangOption = SUPPORTED_LANGUAGES.find(l => l.code === language) || SUPPORTED_LANGUAGES[0];
  const dir = currentLangOption.dir;

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    localStorage.setItem('apkforge_language', lang);
  };

  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = language;
  }, [dir, language]);

  const t = (key: string, defaultText?: string) => {
    return getTranslation(language, key, defaultText);
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, dir, currentLangOption }}>
      {children}
    </LanguageContext.Provider>
  );
};
